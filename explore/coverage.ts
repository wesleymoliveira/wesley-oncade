// Builds docs/api-coverage.md from explore/endpoints.json (the 75 endpoints
// of the reference) and explore/results (what each exploration script saw).
//
//   npm run explore:coverage

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Endpoint {
  endpoint: string;
  name: string;
  family: string;
}
interface Result {
  family: string;
  at: string;
  calls: { endpoint: string; status: number; code: string | null }[];
  answers: Record<string, string>;
}

const here = import.meta.dirname;
const endpoints = JSON.parse(readFileSync(join(here, 'endpoints.json'), 'utf8')) as Endpoint[];
const results = readdirSync(join(here, 'results'))
  .filter((file) => file.endsWith('.json'))
  .map((file) => JSON.parse(readFileSync(join(here, 'results', file), 'utf8')) as Result);

/** Why an endpoint was left alone, when that was a decision and not a gap. */
const LEFT_ALONE: Record<string, string> = {
  'POST /grants/{grantId}/revoke': 'Not called on purpose: it would cut this platform off from its only business',
  'POST /business': 'Not called: it creates a business that no call can remove',
  'PATCH /business': 'Not called: the record is a real business',
};

const seen = new Map<string, Set<string>>();
for (const result of results) {
  for (const call of result.calls) {
    const answers = seen.get(call.endpoint) ?? new Set<string>();
    answers.add(call.code ? `${call.status} ${call.code}` : String(call.status));
    seen.set(call.endpoint, answers);
  }
}
const reached = (endpoint: string) =>
  [...(seen.get(endpoint) ?? [])].some((answer) => !answer.includes('SCOPE_NOT_GRANTED'));
const succeeded = (endpoint: string) =>
  [...(seen.get(endpoint) ?? [])].some((answer) => Number(answer.slice(0, 3)) < 300);
const families = [...new Set(endpoints.map((entry) => entry.family))];
const exercised = endpoints.filter((entry) => reached(entry.endpoint)).length;

const lines: string[] = [
  '# The Platform API, call by call',
  '',
  `The reference lists ${endpoints.length} endpoints. This project has called **${exercised}** of them against the test environment.`,
  `**${endpoints.filter((entry) => succeeded(entry.endpoint)).length}** answered with a success at least once. The others answered only with a refusal or an error, and the table says which.`,
  'The few that were not called were left alone on purpose, and the reason is in the table.',
  'This page is generated by `npm run explore:coverage` from what the scripts in [`explore/`](../explore/) recorded: statuses and error codes, nothing else.',
  '',
  'Every family was asked the same questions: does the happy path work, what does a bad request answer, does a repeated `Idempotency-Key` make a duplicate, what does a call in the wrong state answer, and which webhooks arrive.',
  '',
  '| Family | Endpoints | Called | With a success |',
  '| --- | --- | --- | --- |',
  ...families.map((family) => {
    const own = endpoints.filter((entry) => entry.family === family);
    const called = own.filter((entry) => reached(entry.endpoint)).length;
    return `| ${family} | ${own.length} | ${called} | ${own.filter((entry) => succeeded(entry.endpoint)).length} |`;
  }),
  '',
  '## What the API answered',
  '',
];
for (const result of results.sort((a, b) => a.family.localeCompare(b.family))) {
  lines.push(`### ${result.family} (${result.at})`, '');
  for (const [question, text] of Object.entries(result.answers)) lines.push(`- **${question}:** ${text}`);
  lines.push('');
}
lines.push('## Every endpoint', '');
for (const family of families) {
  lines.push(`### ${family}`, '', '| Endpoint | Answers seen |', '| --- | --- |');
  for (const entry of endpoints.filter((item) => item.family === family)) {
    const answers = [...(seen.get(entry.endpoint) ?? [])].sort();
    const text =
      answers.length > 0
        ? answers.map((answer) => `\`${answer}\``).join(', ')
        : (LEFT_ALONE[entry.endpoint] ?? 'Not yet');
    lines.push(`| \`${entry.endpoint}\` | ${text} |`);
  }
  lines.push('');
}
writeFileSync(join(here, '..', 'docs', 'api-coverage.md'), `${lines.join('\n')}`);
console.log(
  `${exercised} of ${endpoints.length} endpoints exercised; docs/api-coverage.md written. Now run: npm run format`,
);
